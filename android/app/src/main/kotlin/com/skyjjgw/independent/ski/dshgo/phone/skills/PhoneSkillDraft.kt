package com.skyjjgw.independent.ski.dshgo.phone.skills

import com.skyjjgw.independent.ski.dshgo.phone.PhoneScreen

/** Explicit local rendering only. No model, filesystem, logger or automatic invocation. */
object PhoneSkillDraft {
    enum class Reason { CONFIRMATION_REQUIRED, TRACE_UNAVAILABLE, TRACE_INELIGIBLE, INVALID_NAME, TOO_LARGE }
    sealed interface Result
    sealed interface Ready : Result {
        val owner: PhoneTaskTrace.OwnerKey
        val skillName: String
        val markdown: String
    }
    data class Rejected(val reason: Reason) : Result
    private class Document(override val owner: PhoneTaskTrace.OwnerKey, override val skillName: String,
        override val markdown: String) : Ready

    /** Name is generated by native code, not a path/title/free-text input. Edits require a later validated revision. */
    fun render(trace: PhoneTaskTrace.Snapshot?, skillName: String, userConfirmed: Boolean, userEdited: Boolean = false): Result {
        if (!userConfirmed) return Rejected(Reason.CONFIRMATION_REQUIRED)
        if (trace == null) return Rejected(Reason.TRACE_UNAVAILABLE)
        if (!trace.canDraft) return Rejected(Reason.TRACE_INELIGIBLE)
        if (!Regex("phone-task-[a-f0-9]{32}").matches(skillName)) return Rejected(Reason.INVALID_NAME)
        val markdown = buildString {
            append("---\nname: ").append(skillName)
            append("\ndescription: 手机任务的本地参数化步骤，使用前核对目标与环境\n")
            append("disable-model-invocation: true\nuser-invocable: true\n---\n\n")
            append("# 手机任务步骤草稿\n\n## 目标与参数\n\n")
            if (userEdited) append("这是用户重新整理的步骤模板，顺序可能不同于原任务；不是可执行的历史路线。\n")
            append("目标：{{goal}}。所有参数在本次使用时由用户提供；不要把个人值写回技能。\n")
            append("应用、版本及登录前提未保留：{{application_requirements}}。先核对当前应用与权限。\n")
            append("目标、输入和检查点占位符尚未填写时，停止并询问用户。\n\n")
            append("## 步骤\n\n")
            trace.steps.forEachIndexed { index, step ->
                val n = index + 1
                val screen = if (step.screen == PhoneScreen.BACKGROUND) "后台屏" else "主屏"
                append(n).append(". 在").append(screen).append("重新观察并确认应用 {{app_").append(n).append("}}；")
                append(instruction(step, n)).append("。\n")
                append("   核对 {{check_").append(n).append("}}，不能只凭工具返回正常判断业务完成。历史记录仅表明请求已交给驱动/系统并返回接受；")
                append(if (step.postObservationAvailable) "曾取得允许读取的后置观察，未验证预期变化。\n" else "没有可用的安全后置观察证据。\n")
            }
            append("\n## 必须停下的情况\n\n")
            append("每步都重新读取页面，不复用旧屏幕号、元素号或坐标。目标不唯一、页面/应用不符、权限改变或没有可核对结果时停下，请用户或模型重新判断。\n")
            append("发送、提交、删除、确认付款以及任何不可逆动作必须重新请求用户确认；历史批准与本次保存确认不授予执行许可。\n")
            append("动作返回错误、超时或结果不明时，先观察，不自动重放同一步。密码、验证码与秘密内容由用户处理，不写进技能。\n")
            append("这是一份待核对的本地步骤模板，不是自动回放程序，也没有经过跨版本成功验证。\n")
        }
        if (markdown.toByteArray(Charsets.UTF_8).size > PhoneTaskTrace.MAX_BYTES) return Rejected(Reason.TOO_LARGE)
        return Document(trace.owner, skillName, markdown)
    }

    /** Reviewed native public route summary only; no MethodChannel accepts this text.
     * The caller must bind this exact preview and bundle at a new editor revision. */
    internal fun withRouteSummary(document: Ready, summary: String): Ready? {
        val markdown = buildString {
            append("---\nname: ").append(document.skillName)
            append("\ndescription: 本机公共路线，使用时重新核对应用、目标与许可\n")
            append("disable-model-invocation: true\nuser-invocable: true\n---\n\n")
            append("# 公共路线预览\n\n").append(summary)
            append("\n\n保存确认不授予执行权限。任一步前置、唯一目标、许可或后置不符就停止交回模型；失败或未知不自动重复。\n")
            append("不可逆操作仍须本次独立确认。编辑步骤会移除此数据路线。\n")
        }
        if (markdown.toByteArray(Charsets.UTF_8).size > PhoneTaskTrace.MAX_BYTES) return null
        return Document(document.owner, document.skillName, markdown)
    }

    private fun instruction(step: PhoneTaskTrace.Step, n: Int): String {
        val target = step.anchor?.let { "固定动作词「${anchor(it)}」（仍须核对唯一目标）" } ?: "{{target_$n}}"
        return when (step.action) {
            PhoneTaskTrace.Action.OPEN_APP -> "打开用户指定的应用"
            PhoneTaskTrace.Action.TAP -> "点击$target"
            PhoneTaskTrace.Action.LONG_TAP -> "长按$target"
            PhoneTaskTrace.Action.TYPE -> "向$target 输入 {{input_$n}}"
            PhoneTaskTrace.Action.TYPE_SUBMIT -> "向$target 输入 {{input_$n}}，提交前重新确认"
            PhoneTaskTrace.Action.SCROLL_UP -> "向上滚动用户确认的区域 {{target_$n}}"
            PhoneTaskTrace.Action.SCROLL_DOWN -> "向下滚动用户确认的区域 {{target_$n}}"
            PhoneTaskTrace.Action.SCROLL_LEFT -> "向左滚动用户确认的区域 {{target_$n}}"
            PhoneTaskTrace.Action.SCROLL_RIGHT -> "向右滚动用户确认的区域 {{target_$n}}"
            PhoneTaskTrace.Action.KEY_BACK -> "按返回键"
            PhoneTaskTrace.Action.KEY_HOME -> "回到桌面"
            PhoneTaskTrace.Action.KEY_RECENTS -> "打开最近任务"
            PhoneTaskTrace.Action.KEY_NOTIFICATIONS -> "打开通知栏"
        }
    }

    private fun anchor(value: PhoneTaskTrace.Anchor): String = when (value) {
        PhoneTaskTrace.Anchor.SEARCH -> "搜索"
        PhoneTaskTrace.Anchor.NEXT -> "下一步"
        PhoneTaskTrace.Anchor.BACK -> "返回"
        PhoneTaskTrace.Anchor.CANCEL -> "取消"
        PhoneTaskTrace.Anchor.CONFIRM -> "确认"
        PhoneTaskTrace.Anchor.SAVE -> "保存"
        PhoneTaskTrace.Anchor.SEND -> "发送"
        PhoneTaskTrace.Anchor.SUBMIT -> "提交"
        PhoneTaskTrace.Anchor.DELETE -> "删除"
    }
}
