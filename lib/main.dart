/// Web keeps its phone preview frame; Android uses the actual safe display area.
class MobilePreviewStage extends StatelessWidget {
  const MobilePreviewStage({super.key, required this.child});
  final Widget child;
  @override
  Widget build(BuildContext context) {
    if (!kIsWeb && defaultTargetPlatform == TargetPlatform.android) {
      return Material(
        color: Theme.of(context).scaffoldBackgroundColor,
        // SkiShell applies system insets and keyboard resizing once.
        child: MediaQuery(
          data: MediaQuery.of(
            context,
          ).copyWith(textScaler: TextScaler.linear(demo.textScale)),
          child: child,
        ),
      );
    }
    return LayoutBuilder(
      builder: (context, bounds) {
        final framed = bounds.maxWidth >= 600;
        final width = math.min(430.0, bounds.maxWidth);
        final height = framed
            ? math.min(932.0, bounds.maxHeight - 28)
            : bounds.maxHeight;
        final screenHeight = height - (framed ? 36 : 0);
        return Material(
          color: const Color(0xffe8edf4),
          child: Center(
            child: Container(
              width: width,
              height: height,
              decoration: BoxDecoration(
                color: Theme.of(context).scaffoldBackgroundColor,
                borderRadius: BorderRadius.circular(framed ? 30 : 0),
                border: framed
                    ? Border.all(color: const Color(0xffbbc9da), width: 1)
                    : null,
                boxShadow: framed
                    ? [
                        BoxShadow(
                          color: ink.withValues(alpha: .1),
                          blurRadius: 36,
                          offset: const Offset(0, 12),
                        ),
                      ]
                    : null,
              ),
              child: ClipRRect(
                borderRadius: BorderRadius.circular(framed ? 29 : 0),
                child: Column(
                  children: [
                    if (framed)
                      SizedBox(
                        height: 36,
                        child: Padding(
                          padding: const EdgeInsets.symmetric(horizontal: 24),
                          child: Row(
                            children: [
                              label('9:41', size: 11, weight: FontWeight.w600),
                              const Spacer(),
                              const Icon(Icons.signal_cellular_alt, size: 14),
                              const SizedBox(width: 5),
                              const Icon(Icons.wifi, size: 14),
                              const SizedBox(width: 5),
                              const Icon(Icons.battery_full, size: 16),
                            ],
                          ),
                        ),
                      ),
                    Expanded(
                      child: MediaQuery(
                        data: MediaQuery.of(context).copyWith(
                          size: Size(width, screenHeight),
                          padding: EdgeInsets.zero,
                          textScaler: TextScaler.linear(demo.textScale),
                        ),
                        child: child,
                      ),
                    ),
                  ],
                ),
              ),
            ),
          ),
        );
      },
    );
  }
}

class SkiShell extends StatefulWidget {
  const SkiShell({super.key, required this.route});
  final String route;
  @override
  State<SkiShell> createState() => _SkiShellState();
}

class _SkiShellState extends State<SkiShell>
    with SingleTickerProviderStateMixin {
  late final DrawerMotion motion;
  @override
  void initState() {
    super.initState();
    motion = DrawerMotion(vsync: this);
  }

  @override
  void dispose() {
    motion.dispose();
    super.dispose();
  }

  void panel(int direction) => motion.toggle(direction);
  void go(String route) => Navigator.of(context).pushReplacementNamed(route);
  String get title => switch (widget.route) {
    '/chat' => demo.role.name,
    '/characters' => '角色',
    '/characters/edit' => '角色卡',
    '/call' => '语音通话',
    '/plugins' => '插件',
    '/market' => '插件市场',
    '/settings' => '设置',
    _ =>
      settingsSections
              .where((s) => widget.route == '/settings/${s.$1}')
              .firstOrNull
              ?.$2 ??
          'ski',
  };
  @override
  Widget build(BuildContext context) => LayoutBuilder(
    builder: (context, box) {
      motion.configure(
        math.min(330, box.maxWidth * .82),
        math.min(350, box.maxWidth * .86),
        reduced: demo.prefs['减少动态效果'] ?? false,
      );
      // Stable subtrees: drag ticks update transforms in SlideDeck, not chat layout.
      final body = widget.route == '/chat'
          ? ChatPage(
              openWorkspace: () => panel(-1),
              openCall: () => go('/call'),
              openModels: () => go('/settings/models'),
            )
          : ContentPage(route: widget.route, go: go);
      final navigation = RepaintBoundary(
        child: SkiGlassPanel(
          child: SafeArea(
            child: SideNavigation(
              route: widget.route,
              go: go,
              close: motion.close,
            ),
          ),
        ),
      );
      final workspace = RepaintBoundary(
        child: SkiGlassPanel(
          leftSide: false,
          child: SafeArea(child: WorkspacePanel(close: motion.close)),
        ),
      );
      final capsule = appearance.flag('capsuleToolbar');
      final foreground = Material(
        color: Colors.transparent,
        child: SafeArea(
          child: Column(
            children: [
              Padding(
                padding: capsule
                    ? const EdgeInsets.fromLTRB(10, 7, 10, 5)
                    : EdgeInsets.zero,
                child: ConfigurableGlassSurface(
                  area: 'toolbarBlur',
                  radius: capsule ? 26 : 0,
                  child: SizedBox(
                    height: 62,
                    child: Padding(
                      padding: const EdgeInsets.symmetric(horizontal: 8),
                      child: Row(
                        children: [
                          SkiGlassButton(
                            tooltip: '打开导航',
                            plain: !capsule,
                            onPressed: () => panel(1),
                            icon: Icons.menu_rounded,
                          ),
                          const SizedBox(width: 9),
                          Expanded(
                            child: Row(
                              children: [
                                Flexible(
                                  child: label(
                                    title,
                                    size: 17,
                                    weight: FontWeight.w600,
                                  ),
                                ),
                                const SizedBox(width: 10),
                              ],
                            ),
                          ),
                          if (widget.route == '/chat')
                            SkiGlassButton(
                              tooltip: '语音通话演示',
                              plain: !capsule,
                              onPressed: () => go('/call'),
                              icon: Icons.call_outlined,
                            ),
                          if (widget.route != '/chat')
                            SkiGlassButton(
                              tooltip: '返回聊天',
                              plain: !capsule,
                              onPressed: () => go('/chat'),
                              icon: Icons.chat_bubble_outline,
                            ),
                          SkiGlassButton(
                            tooltip: '打开工作区',
                            plain: !capsule,
                            onPressed: () => panel(-1),
                            icon: Icons.space_dashboard_outlined,
                          ),
                        ],
                      ),
                    ),
                  ),
                ),
              ),
              Expanded(child: RepaintBoundary(child: body)),
            ],
          ),
        ),
      );
      return Scaffold(
        backgroundColor: Colors.transparent,
        body: SkiGlassScene(
          motion: motion,
          // Sheets fill the display; only their foregrounds keep safe insets.
          child: BackdropGroup(
            child: SlideDeck(
              motion: motion,
              left: navigation,
              right: workspace,
              child: foreground,
            ),
          ),
        ),
      );
    },
  );
}

