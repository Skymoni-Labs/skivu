/// Web keeps its phone preview frame; Android uses the actual safe display area.
class MobilePreviewStage extends StatelessWidget {
  const MobilePreviewStage({super.key, required this.child});
  final Widget child;
  @override
  Widget build(BuildContext context) {
    if (!kIsWeb && defaultTargetPlatform == TargetPlatform.android) {
      return Material(
        color: Theme.of(context).scaffoldBackgroundColor,
        // SkiShell applies system insets and keyboard resizing once.
        child: MediaQuery(
          data: MediaQuery.of(
            context,
          ).copyWith(textScaler: TextScaler.linear(demo.textScale)),
          child: child,
        ),
      );
    }
    return LayoutBuilder(
      builder: (context, bounds) {
        final framed = bounds.maxWidth >= 600;
        final width = math.min(430.0, bounds.maxWidth);
        final height = framed
            ? math.min(932.0, bounds.maxHeight - 28)
            : bounds.maxHeight;
        final screenHeight = height - (framed ? 36 : 0);
        return Material(
          color: const Color(0xffe8edf4),
          child: Center(
            child: Container(
              width: width,
              height: height,
              decoration: BoxDecoration(
                color: Theme.of(context).scaffoldBackgroundColor,
                borderRadius: BorderRadius.circular(framed ? 30 : 0),
                border: framed
                    ? Border.all(color: const Color(0xffbbc9da), width: 1)
                    : null,
                boxShadow: framed
                    ? [
                        BoxShadow(
                          color: ink.withValues(alpha: .1),
                          blurRadius: 36,
                          offset: const Offset(0, 12),
                        ),
                      ]
                    : null,
              ),
              child: ClipRRect(
                borderRadius: BorderRadius.circular(framed ? 29 : 0),
                child: Column(
                  children: [
                    if (framed)
                      SizedBox(
                        height: 36,
                        child: Padding(
                          padding: const EdgeInsets.symmetric(horizontal: 24),
                          child: Row(
                            children: [
                              label('9:41', size: 11, weight: FontWeight.w600),
                              const Spacer(),
                              const Icon(Icons.signal_cellular_alt, size: 14),
                              const SizedBox(width: 5),
                              const Icon(Icons.wifi, size: 14),
                              const SizedBox(width: 5),
                              const Icon(Icons.battery_full, size: 16),
                            ],
                          ),
                        ),
                      ),
                    Expanded(
                      child: MediaQuery(
                        data: MediaQuery.of(context).copyWith(
                          size: Size(width, screenHeight),
                          padding: EdgeInsets.zero,
                          textScaler: TextScaler.linear(demo.textScale),
                        ),
                        child: child,
                      ),
                    ),
                  ],
                ),
              ),
            ),
          ),
        );
      },
    );
  }
}

class SkiShell extends StatefulWidget {
  const SkiShell({super.key, required this.route});
  final String route;
  @override
  State<SkiShell> createState() => _SkiShellState();
}

class _SkiShellState extends State<SkiShell>
    with SingleTickerProviderStateMixin {
  late final DrawerMotion motion;
  @override
  void initState() {
    super.initState();
    motion = DrawerMotion(vsync: this);
  }

  @override
  void dispose() {
    motion.dispose();
    super.dispose();
  }

  void panel(int direction) => motion.toggle(direction);
  void go(String route) => Navigator.of(context).pushReplacementNamed(route);
  String get title => switch (widget.route) {
    '/chat' => demo.role.name,
    '/characters' => '角色',
    '/characters/edit' => '角色卡',
    '/call' => '语音通话',
    '/plugins' => '插件',
    '/market' => '插件市场',
    '/settings' => '设置',
    _ =>
      settingsSections
              .where((s) => widget.route == '/settings/${s.$1}')
              .firstOrNull
              ?.$2 ??
          appName,
  };
  @override
  Widget build(BuildContext context) => LayoutBuilder(
    builder: (context, box) {
      motion.configure(
        math.min(330, box.maxWidth * .82),
        math.min(350, box.maxWidth * .86),
        reduced: demo.prefs['减少动态效果'] ?? false,
      );
      // Stable subtrees: drag ticks update transforms in SlideDeck, not chat layout.
      final body = widget.route == '/chat'
          ? ChatPage(
              openWorkspace: () => panel(-1),
              openCall: () => go('/call'),
              openModels: () => go('/settings/models'),
            )
          : ContentPage(route: widget.route, go: go);
      final navigation = RepaintBoundary(
        child: SkiGlassPanel(
          child: SafeArea(
            child: SideNavigation(
              route: widget.route,
              go: go,
              close: motion.close,
            ),
          ),
        ),
      );
      final workspace = RepaintBoundary(
        child: SkiGlassPanel(
          leftSide: false,
          child: SafeArea(child: WorkspacePanel(close: motion.close)),
        ),
      );
      final capsule = appearance.flag('capsuleToolbar');
      final toolbar = SizedBox(
        key: ValueKey(capsule ? 'capsule-toolbar' : 'rectangle-toolbar'),
        height: 62,
        child: Padding(
          padding: const EdgeInsets.symmetric(horizontal: 8),
          child: Row(
            children: [
              SkiGlassButton(
                tooltip: '打开导航',
                plain: true,
                onPressed: () => panel(1),
                icon: Icons.menu_rounded,
              ),
              const SizedBox(width: 8),
              Expanded(
                child: Column(
                  mainAxisAlignment: MainAxisAlignment.center,
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    InkWell(
                      onTap: widget.route == '/chat'
                          ? () => go('/characters/edit')
                          : null,
                      child: Text(
                        title,
                        maxLines: 1,
                        overflow: TextOverflow.ellipsis,
                        style: const TextStyle(
                          fontSize: 16,
                          fontWeight: FontWeight.w600,
                          color: ink,
                        ),
                      ),
                    ),
                    if (widget.route == '/chat' && demo.streaming)
                      const Text(
                        '对方正在输入中',
                        key: ValueKey('typing-indicator'),
                        style: TextStyle(fontSize: 11, color: ink),
                      ),
                  ],
                ),
              ),
              SkiGlassButton(
                tooltip: widget.route == '/chat' ? '语音通话' : '返回聊天',
                plain: true,
                onPressed: () =>
                    go(widget.route == '/chat' ? '/call' : '/chat'),
                icon: widget.route == '/chat'
                    ? Icons.call_outlined
                    : Icons.chat_bubble_outline,
              ),
              SkiGlassButton(
                tooltip: '打开工作区',
                plain: true,
                onPressed: () => panel(-1),
                icon: Icons.space_dashboard_outlined,
              ),
            ],
          ),
        ),
      );
      final foreground = Material(
        color: Colors.transparent,
        child: SafeArea(
          top: false,
          child: Stack(
            children: [
              Positioned.fill(
                child: widget.route == '/chat'
                    ? RepaintBoundary(child: body)
                    : Padding(
                        padding: EdgeInsets.only(
                          top: 76 + MediaQuery.paddingOf(context).top,
                        ),
                        child: RepaintBoundary(child: body),
                      ),
              ),
              Positioned(
                top: 0,
                left: 0,
                right: 0,
                child: capsule
                    ? Padding(
                        padding: EdgeInsets.fromLTRB(
                          10,
                          MediaQuery.paddingOf(context).top + 7,
                          10,
                          5,
                        ),
                        child: ClipRRect(
                          borderRadius: BorderRadius.circular(40),
                          child: ConfigurableGlassSurface(
                            area: 'toolbarBlur',
                            radius: 40,
                            child: toolbar,
                          ),
                        ),
                      )
                    : ConfigurableGlassSurface(
                        key: const ValueKey('glass-rectangle-toolbar'),
                        area: 'toolbarBlur',
                        radius: 0,
                        child: Padding(
                          padding: EdgeInsets.only(
                            top: MediaQuery.paddingOf(context).top,
                          ),
                          child: toolbar,
                        ),
                      ),
              ),
            ],
          ),
        ),
      );
      if (widget.route == '/call') return Scaffold(body: body);
      return Scaffold(
        backgroundColor: Colors.transparent,
        body: SkiGlassScene(
          motion: motion,
          // Sheets fill the display; only their foregrounds keep safe insets.
          child: BackdropGroup(
            child: SlideDeck(
              motion: motion,
              left: navigation,
              right: workspace,
              child: foreground,
            ),
          ),
        ),
      );
    },
  );
}

