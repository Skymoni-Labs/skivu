class SkiShell extends StatefulWidget {
  const SkiShell({super.key, required this.route});
  final String route;
  @override
  State<SkiShell> createState() => _SkiShellState();
}

class _SkiShellState extends State<SkiShell>
    with SingleTickerProviderStateMixin {
  final _foregroundKey = GlobalKey();
  late final DrawerMotion motion;
  @override
  void initState() {
    super.initState();
    motion = DrawerMotion(vsync: this);
  }

  @override
  void dispose() {
    motion.dispose();
    super.dispose();
  }

  void panel(int direction) => motion.toggle(direction);
  void go(String route) => Navigator.of(context).pushReplacementNamed(route);
  void returnHome(bool didPop, Object? result) {
    if (didPop) return;
    if (motion.offset.abs() > .1 || motion.dragging) motion.close();
    if (widget.route == '/chat' && uiPlugins.mode != ChatUiMode.classic) {
      uiPlugins.showHome();
      return;
    }
    if (widget.route != '/chat') go('/chat');
  }

  String get title => switch (widget.route) {
    '/chat' => demo.role.name,
    '/characters' => '角色',
    '/characters/edit' => '角色卡',
    '/call' => '语音通话',
    '/plugins' => '插件',
    '/market' => '插件市场',
    '/settings' => '设置',
    _ =>
      settingsSections
              .where((s) => widget.route == '/settings/${s.$1}')
              .firstOrNull
              ?.$2 ??
          appName,
  };
  @override
  Widget build(BuildContext context) => PopScope<Object?>(
    canPop: false,
    onPopInvokedWithResult: returnHome,
    child: _shell(context),
  );

  Widget _shell(BuildContext context) => LayoutBuilder(
    builder: (context, box) {
      motion.configure(
        math.min(330, box.maxWidth * .82),
        math.min(350, box.maxWidth * .86),
        reduced: demo.prefs['减少动态效果'] ?? false,
      );
      // Stable subtrees: drag ticks update transforms in SlideDeck, not chat layout.
      final htmlUi =
          widget.route == '/chat' && uiPlugins.mode != ChatUiMode.classic;
      final body = widget.route == '/chat'
          ? htmlUi
                ? LaunchReveal(
                    part: LaunchPart.content,
                    child: HtmlUiPage(
                      go: go,
                      openNavigation: () {
                        if (motion.offset < .1) panel(1);
                      },
                      openWorkspace: () {
                        if (motion.offset > -.1) panel(-1);
                      },
                    ),
                  )
                : ChatPage(
                    backdropAnchor: _foregroundKey,
                    openWorkspace: () => panel(-1),
                    openCall: () => go('/call'),
                    openModels: () => go('/settings/models'),
                  )
          : ContentPage(route: widget.route, go: go);
      final navigation = RepaintBoundary(
        child: SkiGlassPanel(
          child: SafeArea(
            child: SideNavigation(
              route: widget.route,
              go: go,
              close: motion.close,
            ),
          ),
        ),
      );
      final workspace = RepaintBoundary(
        child: SkiGlassPanel(
          leftSide: false,
          child: SafeArea(child: WorkspacePanel(close: motion.close)),
        ),
      );
      final capsule = appearance.flag('capsuleToolbar');
      final typing = widget.route == '/chat' && demo.streaming;
      final toolbar = SizedBox(
        key: ValueKey(capsule ? 'capsule-toolbar' : 'rectangle-toolbar'),
        height: appToolbarHeight,
        child: Padding(
          padding: const EdgeInsets.symmetric(horizontal: 8),
          child: Row(
            children: [
              SkiGlassButton(
                tooltip: '打开导航',
                plain: true,
                onPressed: () => panel(1),
                icon: Icons.menu_rounded,
              ),
              const SizedBox(width: 8),
              Expanded(
                child: InkWell(
                  onTap: widget.route == '/chat'
                      ? () {
                          demo.editCurrentRole();
                          go('/characters/edit');
                        }
                      : null,
                  child: Text(
                    typing ? '对方正在输入中...' : title,
                    key: ValueKey(
                      typing ? 'typing-indicator' : 'toolbar-title',
                    ),
                    maxLines: 1,
                    overflow: TextOverflow.ellipsis,
                    style: TextStyle(
                      fontSize: 16,
                      fontWeight: FontWeight.w600,
                      color: ink,
                    ),
                  ),
                ),
              ),
              SkiGlassButton(
                tooltip: widget.route == '/chat' ? '语音通话' : '返回聊天',
                plain: true,
                onPressed: () =>
                    go(widget.route == '/chat' ? '/call' : '/chat'),
                icon: widget.route == '/chat'
                    ? Icons.call_outlined
                    : Icons.chat_bubble_outline,
              ),
              SkiGlassButton(
                tooltip: '打开工作区',
                plain: true,
                onPressed: () => panel(-1),
                icon: Icons.space_dashboard_outlined,
              ),
            ],
          ),
        ),
      );
      final foreground = Material(
        key: _foregroundKey,
        color: Colors.transparent,
        child: SafeArea(
          top: false,
          child: Stack(
            children: [
              Positioned.fill(
                child: widget.route == '/chat'
                    ? body
                    : Padding(
                        padding: EdgeInsets.only(
                          top:
                              appToolbarHeight +
                              8 +
                              MediaQuery.paddingOf(context).top,
                        ),
                        child: RepaintBoundary(child: body),
                      ),
              ),
              if (!htmlUi)
                Positioned(
                  top: 0,
                  left: 0,
                  right: 0,
                  child: capsule
                      ? Padding(
                          padding: EdgeInsets.fromLTRB(
                            10,
                            MediaQuery.paddingOf(context).top + 2,
                            10,
                            5,
                          ),
                          child: LaunchReveal(
                            part: LaunchPart.toolbar,
                            radius: 40,
                            child: ClipRRect(
                              borderRadius: BorderRadius.circular(40),
                              child: ConfigurableGlassSurface(
                                area: 'toolbarBlur',
                                radius: 40,
                                child: toolbar,
                              ),
                            ),
                          ),
                        )
                      : LaunchReveal(
                          part: LaunchPart.toolbar,
                          child: ConfigurableGlassSurface(
                            key: const ValueKey('glass-rectangle-toolbar'),
                            area: 'toolbarBlur',
                            radius: 0,
                            child: Padding(
                              padding: EdgeInsets.only(
                                top: MediaQuery.paddingOf(context).top,
                              ),
                              child: toolbar,
                            ),
                          ),
                        ),
                ),
            ],
          ),
        ),
      );
      if (widget.route == '/call') return Scaffold(body: body);
      return Scaffold(
        backgroundColor: Colors.transparent,
        body: SkiGlassScene(
          motion: motion,
          cacheChatBackdrop: uiPlugins.mode != ChatUiMode.classic,
          // Sheets fill the display; only their foregrounds keep safe insets.
          child: BackdropGroup(
            child: SlideDeck(
              motion: motion,
              left: navigation,
              right: workspace,
              child: foreground,
            ),
          ),
        ),
      );
    },
  );
}

