    yield LicenseEntryWithLineBreaks([
      'Noto Sans SC',
    ], await rootBundle.loadString('licenses/NotoSansSC-OFL.txt'));
    yield LicenseEntryWithLineBreaks([
      'Material Icons font · Google · subset generated by Flutter',
    ], await rootBundle.loadString('licenses/MaterialIcons-CC-BY-4.0.txt'));
    yield LicenseEntryWithLineBreaks([
      'Noto Serif SC',
    ], await rootBundle.loadString('licenses/NotoSerifSC-OFL.txt'));
    yield LicenseEntryWithLineBreaks([
      'Roboto Mono',
    ], await rootBundle.loadString('licenses/RobotoMono-OFL.txt'));
  });
  await Future.wait([
    wallpaper.restore(),
    glassPreferences.restore(),
    appearance.restore(),
  ]);
  await appearanceProfiles.restore();
  await modelSettings.restore();
  await betaAccess.restore();
  await demo.restore();
  await recoverInterruptedMedia();
